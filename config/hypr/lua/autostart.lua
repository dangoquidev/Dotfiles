local p = require("lua.programs")

hl.on("hyprland.start", function()
    hl.exec_cmd("waybar")
    hl.exec_cmd("quickshell -c shell")   -- volume/brightness OSD, clipboard panel
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    hl.exec_cmd("hypridle")
    hl.exec_cmd("fcitx5 -d --replace")   -- input methods: US intl / AZERTY / pinyin (SUPER+Space)
    hl.exec_cmd("hyprsunset")
    hl.exec_cmd("~/.config/hypr/scripts/battery-notify.sh")
    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("wl-paste --type image --watch cliphist store")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface gtk-theme 'catppuccin-mocha-pink-standard+default'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface cursor-theme 'catppuccin-mocha-pink-cursors'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface cursor-size 24")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface font-name 'Maple Mono NF CN 11'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface document-font-name 'Maple Mono NF CN 11'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface monospace-font-name 'Maple Mono NF CN 11'")
    hl.exec_cmd("gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark'")
    hl.exec_cmd("awww-daemon")
    -- last wallpaper (or the default) + lockscreen image, once the daemon answers
    hl.exec_cmd("~/.config/hypr/scripts/wallpaper.sh --restore")
end)
